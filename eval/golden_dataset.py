def build_golden_dataset_file(output_path: str = "eval/golden_v1.csv") -> str:
    """Write the golden dataset to CSV and return validation report."""
    report = validate_dataset(GOLDEN_CASES)
    if not report["is_valid"]:
        raise ValueError(f"Dataset validation failed: {json.dumps(report['errors'], indent=2)}")

    save_golden_dataset(GOLDEN_CASES, output_path)
    dataset_hash = compute_dataset_hash(GOLDEN_CASES)

    print(f"Wrote {len(GOLDEN_CASES)} cases to {output_path}")
    print(f"Dataset version: {DATASET_VERSION}")
    print(f"Dataset hash: {dataset_hash}")
    print(f"Validation: {'PASSED' if report['is_valid'] else 'FAILED'}")
    return dataset_hash


