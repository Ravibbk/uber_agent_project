VALID_ESCALATIONS = {"AUTO_HANDLE", "ESCALATE"}
VALID_RISK_CATEGORIES = {"none", "safety", "legal", "ambiguous", "adversarial", "edge_case"}
VALID_SOURCES = {"synthetic", "real_twcs", "reviewed", "fault_injection"}
VALID_ANNOTATION_STATUSES = {"reviewed", "pending_review", "auto_suggested"}

REQUIRED_FIELDS = [
    "case_id", "dataset_version", "customer_message", "expected_intent",
    "expected_escalation", "risk_category", "source", "annotation_status",
]


def validate_case(case: dict) -> list[str]:
    """Validate a single evaluation case. Returns list of errors (empty = valid)."""
    errors = []

    for field in REQUIRED_FIELDS:
        if field not in case or case[field] is None:
            errors.append(f"Missing required field: {field}")
        elif field != "customer_message" and not str(case[field]).strip():
            errors.append(f"Empty required field: {field}")

    if case.get("expected_intent") and case["expected_intent"] not in VALID_INTENTS:
        errors.append(f"Invalid intent: {case['expected_intent']}")

    if case.get("expected_escalation") and case["expected_escalation"] not in VALID_ESCALATIONS:
        errors.append(f"Invalid escalation: {case['expected_escalation']}")

    if case.get("risk_category") and case["risk_category"] not in VALID_RISK_CATEGORIES:
        errors.append(f"Invalid risk_category: {case['risk_category']}")

    if case.get("source") and case["source"] not in VALID_SOURCES:
        errors.append(f"Invalid source: {case['source']}")

    if case.get("annotation_status") and case["annotation_status"] not in VALID_ANNOTATION_STATUSES:
        errors.append(f"Invalid annotation_status: {case['annotation_status']}")

    return errors


def validate_dataset(cases: list[dict]) -> dict:
    """Validate the full dataset. Returns validation report."""
    all_errors = []
    case_ids = set()
    duplicates = []

    for i, case in enumerate(cases):
        errors = validate_case(case)
        if errors:
            all_errors.append({"index": i, "case_id": case.get("case_id", "?"), "errors": errors})

        cid = case.get("case_id")
        if cid in case_ids:
            duplicates.append(cid)
        case_ids.add(cid)

    return {
        "total_cases": len(cases),
        "valid_cases": len(cases) - len(all_errors),
        "errors": all_errors,
        "duplicate_ids": duplicates,
        "dataset_version": cases[0].get("dataset_version", "unknown") if cases else "empty",
        "is_valid": len(all_errors) == 0 and len(duplicates) == 0,
    }


def compute_dataset_hash(cases: list[dict]) -> str:
    """Compute a deterministic hash of the dataset content."""
    content = json.dumps(cases, sort_keys=True, default=str)
    return hashlib.sha256(content.encode()).hexdigest()[:16]


def load_golden_dataset(path: str) -> list[dict]:
    """Load golden dataset from CSV."""
    cases = []
    with open(path, "r", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            cases.append(dict(row))
    return cases


def save_golden_dataset(cases: list[dict], path: str) -> None:
    """Save golden dataset to CSV."""
    if not cases:
        raise ValueError("Cannot save empty dataset")
    fieldnames = list(cases[0].keys())
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(cases)


